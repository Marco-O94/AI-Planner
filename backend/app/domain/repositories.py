class ArtifactRepository(Protocol):
    def add(self, artifact: Artifact) -> Artifact: ...
    def get_by_id(self, artifact_id: uuid.UUID) -> Artifact | None: ...
    def get_by_slug(self, project_id: uuid.UUID, slug: str) -> Artifact | None: ...
    def update(self, artifact: Artifact) -> Artifact: ...
    def delete(self, artifact_id: uuid.UUID) -> None: ...
    def set_current_version(self, artifact_id: uuid.UUID, version_id: uuid.UUID) -> None: ...
    def list(
        self, project_id: uuid.UUID, *, artifact_type_id: uuid.UUID | None = None
    ) -> list[Artifact]: ...
    # versions / files / phases
    def add_version(self, version: ArtifactVersion) -> ArtifactVersion: ...
    def next_version_number(self, artifact_id: uuid.UUID) -> int: ...
    def list_versions(self, artifact_id: uuid.UUID) -> list[ArtifactVersion]: ...
    def get_version(
        self, artifact_id: uuid.UUID, version_number: int
    ) -> ArtifactVersion | None: ...
    def get_version_by_id(self, version_id: uuid.UUID) -> ArtifactVersion | None: ...
    def add_files(self, files: list[ArtifactFile]) -> list[ArtifactFile]: ...
    def list_files(self, version_id: uuid.UUID) -> list[ArtifactFile]: ...
    def add_phases(self, phases: list[ArtifactPhase]) -> list[ArtifactPhase]: ...
    def list_phases(self, version_id: uuid.UUID) -> list[ArtifactPhase]: ...
    def get_phase(self, phase_id: uuid.UUID) -> ArtifactPhase | None: ...
    def update_phase(self, phase: ArtifactPhase) -> ArtifactPhase: ...
    # reverse lookups
    def list_by_source_note(self, note_id: uuid.UUID) -> list[Artifact]: ...
    def list_by_source_task(self, task_id: uuid.UUID) -> list[Artifact]: ...
    def iter_indexable_files(self) -> list[IndexableFile]: ...


