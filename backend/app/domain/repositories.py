"""Repository interfaces (Protocols).

Application services depend on these abstractions, not on SQLAlchemy. The
infrastructure layer provides concrete implementations. Methods exchange domain
entities / read models and primitives only — never ORM objects or Pydantic DTOs.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import Protocol

from app.domain.entities import (
    Artifact,
    ArtifactFile,
    ArtifactPhase,
    ArtifactType,
    ArtifactVersion,
    Document,
    Domain,
    Note,
    NoteTypeEntity,
    Project,
    ProjectTemplate,
    Skill,
    Task,
    Technology,
)
from app.domain.enums import (
    ArtifactStatus,
    ProjectStatus,
    ScopeKind,
    TaskPriority,
    TaskStatus,
    TechnologyKind,
)
from app.domain.read_models import ProjectDetail, ProjectTechnologyRef
from app.domain.search import IndexableFile


class ProjectRepository(Protocol):
    def add(self, project: Project) -> Project: ...
    def get_by_id(self, project_id: uuid.UUID) -> Project | None: ...
    def get_by_slug(self, slug: str) -> Project | None: ...
    def get_detail_by_slug(self, slug: str) -> ProjectDetail | None: ...
    def update(self, project: Project) -> Project: ...
    def delete(self, project_id: uuid.UUID) -> None: ...
    def slug_exists(self, slug: str) -> bool: ...
    def list(
        self,
        *,
        search: str | None = None,
        language: str | None = None,
        framework: str | None = None,
        database: str | None = None,
        status: ProjectStatus | None = None,
    ) -> list[ProjectDetail]: ...
    def attach_technology(
        self, project_id: uuid.UUID, technology_id: uuid.UUID, version: str | None
    ) -> None: ...
    def detach_technology(self, project_id: uuid.UUID, technology_id: uuid.UUID) -> None: ...
    def list_technologies(self, project_id: uuid.UUID) -> list[ProjectTechnologyRef]: ...


